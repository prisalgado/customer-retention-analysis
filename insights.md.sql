# Customer Retention Analysis Insights

## Purchase Frequency Analysis
- Some customers made significantly more purchases than others.
- Repeat purchases suggest the presence of loyal or highly engaged customers.

## Customer Value Analysis
- The highest-value customer generated nearly $70K more revenue per purchase than the third-ranked customer.
- The top customer achieved an average revenue per purchase of approximately $84K, significantly outperforming the remaining customer base.
- The results suggest the presence of a small group of exceptionally high-value customers contributing disproportionately to revenue.

## Customer Loyalty Analysis
- Some customers demonstrated significantly higher purchase frequency than the overall customer base.
- The results suggest the presence of a loyal customer segment with strong repeat purchasing behaviour.
- High-frequency customers may represent opportunities for retention campaigns, loyalty programs, or personalised marketing initiatives.